import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createRuntime } from "../game/luau-runtime.js";

const dispatch = await createRuntime(path => readFile(new URL("../game/" + path, import.meta.url), "utf8"));
let time = 1000;
const call = async (op, ...args) => Object.values(await dispatch(op, time, ...args));
const action = (user, kind, data) => call("action", user, kind, data);
const code = number => String(number).padStart(36, "0");
for (let user = 1; user <= 13; user++) await call("join", user, "Player " + user);
const states = events => events.filter(event => event.kind === "state");

assert.equal(states(await action(1, "createInvite", { code: code(1), baseSeconds: 60, increment: 2 })).length, 0);
time += 45;
await call("tick");
const waiting = (await action(1, "resume")).find(event => event.kind === "inviteRoom");
assert.equal(waiting.data.count, 1);
assert.equal(waiting.data.baseSeconds, 60);
assert.equal(states(await action(1, "joinInvite", { code: code(1) })).length, 0);
const started = states(await action(2, "joinInvite", { code: code(1) }));
assert.equal(started.length, 2);
const white = started.find(event => event.data.side === "w");
const black = started.find(event => event.data.side === "b");
assert.deepEqual(white.data.clocks, { w: 60, b: 60 });
assert.equal(white.data.turnStarted, time);
assert.equal((await action(3, "joinInvite", { code: code(1) }))[0].kind, "reject");

time += 6;
const moved = states(await action(white.user, "move", { from: "e2", to: "e4" }));
assert.equal(moved.length, 2);
assert.deepEqual(moved[0].data.clocks, { w: 56, b: 60 });
assert.equal(moved[0].data.turnStarted, time);
time += 60;
const flagged = (await call("tick")).filter(event => event.kind === "result");
assert.equal(flagged.find(event => event.user === black.user).data.reason, "Timeout");
assert.equal(flagged[0].data.clocks.b, 0);

await action(4, "createInvite", { code: code(4), four: true, baseSeconds: 120, increment: 1 });
await action(5, "joinInvite", { code: code(4) });
await action(6, "joinInvite", { code: code(4) });
const duplicate = await action(5, "joinInvite", { code: code(4) });
assert.equal(duplicate.find(event => event.kind === "inviteRoom").data.count, 3);
await action(6, "leaveInvite");
assert.equal((await action(4, "resume")).find(event => event.kind === "inviteRoom").data.count, 2);
await action(7, "joinInvite", { code: code(4) });
const four = states(await action(8, "joinInvite", { code: code(4) }));
assert.equal(four.length, 4);
assert.equal(new Set(four.map(event => event.data.side)).size, 4);
assert.deepEqual(four[0].data.clocks, { R: 120, B: 120, Y: 120, G: 120 });
const red = four.find(event => event.data.side === "R");
time += 5;
const fourMoved = states(await action(red.user, "move", { from: "h2", to: "h4" }));
assert.equal(fourMoved.length, 4);
assert.equal(fourMoved[0].data.state.turn, "B");
assert.equal(fourMoved[0].data.clocks.R, 116);
assert.equal(fourMoved[0].data.turnStarted, time);
time += 120;
const afterTimeout = states(await call("tick"))[0].data;
assert.equal(afterTimeout.state.turn, "Y");
assert.equal(afterTimeout.clocks.B, 0);
assert.equal(afterTimeout.turnStarted, time);

await action(9, "createInvite", { code: code(9), four: true });
await action(10, "joinInvite", { code: code(9) });
assert.equal((await action(9, "leaveInvite")).filter(event => event.kind === "inviteClosed").length, 2);
assert.equal((await action(11, "joinInvite", { code: code(9) }))[0].kind, "reject");
assert.equal(states(await action(11, "queue", { baseSeconds: 60 })).length, 0);
assert.equal(states(await action(12, "queue", { baseSeconds: 300 })).length, 0);
const queuedMatch = states(await action(13, "queue", { baseSeconds: 60 }));
assert.deepEqual(queuedMatch.map(event => event.user), [11, 13]);
assert.deepEqual(queuedMatch[0].data.clocks, { w: 60, b: 60 });
console.log("Invite admission, duplicate joins, closure, clock start, increment, timeout and queue controls passed.");
